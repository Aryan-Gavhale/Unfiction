"""Embed images into a script file the toolkit can load from file://.

    python embed_images.py OUT.js IMAGE_OR_FOLDER [IMAGE_OR_FOLDER ...]

Each image is named after its file name: "Suspect 1.jpg" becomes "suspect-1".
Load OUT.js after uf-core.js, then use the name, e.g. { kind: 'photo', image: 'suspect-1' }.
"""
import base64
import pathlib
import re
import sys

TYPES = {".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp", ".gif": "image/gif"}
WARN_BYTES = 1_500_000


def name_for(path: pathlib.Path) -> str:
    return re.sub(r"[^a-z0-9]+", "-", path.stem.lower()).strip("-")


def collect(args: list[str]) -> list[pathlib.Path]:
    files = []
    for arg in args:
        p = pathlib.Path(arg)
        if p.is_dir():
            files += sorted(f for f in p.iterdir() if f.suffix.lower() in TYPES)
        elif p.is_file() and p.suffix.lower() in TYPES:
            files.append(p)
        else:
            sys.exit(f"Not an image or folder: {arg}")
    return files


def main() -> None:
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out = pathlib.Path(sys.argv[1])
    if out.suffix.lower() != ".js":
        sys.exit("OUT must end in .js")
    files = collect(sys.argv[2:])
    if not files:
        sys.exit("No images found.")
    entries, seen = [], {}
    for f in files:
        name = name_for(f)
        if not name:
            sys.exit(f"Cannot make a name from {f.name}")
        if name in seen:
            sys.exit(f"{f.name} and {seen[name].name} would both be called '{name}'. Rename one.")
        seen[name] = f
        data = f.read_bytes()
        if len(data) > WARN_BYTES:
            print(f"warning: {f.name} is {len(data) / 1e6:.1f} MB; resize it to about 800 px wide to keep the page fast.")
        uri = f"data:{TYPES[f.suffix.lower()]};base64,{base64.b64encode(data).decode('ascii')}"
        entries.append(f'  "{name}": "{uri}",')
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "/* Generated by toolkit/tools/embed_images.py. Re-run it instead of editing this file. */\n"
        "UF.addImages({\n" + "\n".join(entries) + "\n});\n",
        encoding="utf-8",
    )
    print(f"{out}: {', '.join(seen)}")


if __name__ == "__main__":
    main()
